// The WiFi TX path under load: lwIP's real TCP and UDP (the firmware's windows and
// buffers, lwip_sim/) sends over a netif whose output is the real wifi_tx_packet on the real DmaUART
// (dma_uart.cc, its TX-done interrupt included) and cmd_buffer.c, with the pool of 12 buffers, over
// the register model of uart_host/dma_uart_regs.h. Time is simulated: the UART moves one frame in
// the time its bytes take at 6.67 Mbaud (about 2.30 ms for 1514 bytes), a fake peer takes each frame
// when it has left the UART and answers it after the round trip time, and the lwIP timers run on the
// simulated clock. Nothing is measured in real time; the CPU time of the Nios is not modelled.
//
// The old behaviour (wifi_tx_wait_legacy: wait for a buffer up to 5 s, the tcpip thread blocked: the
// clock moves with the UART, and nothing else of lwIP runs: not the peer's answers, nor the timers)
// is run beside the new one, on the same load.
//
//   WtxSimThroughput  bytes delivered in 10 s, old against new, RTT 5, 30 and 60 ms
//   WtxSimStall       the module drain stops for 3 s: lwIP responsiveness and the resume
//   WtxSimWake        nothing in flight, the pool taken by other frames: only the wake restarts TCP
//
// -DWTX_NEW_IS_LEGACY puts the old function in the place of the new one (a red model).

