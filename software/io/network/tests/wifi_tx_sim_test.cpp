// ---- 1. Throughput, a bulk stream for 10 seconds ---------------------------------------------
// One connection at three round trip times: its 16 KB of send buffer (11 segments) cannot take the
// pool of 12 down to the reserve by itself, so nothing is refused. Two connections can: 22 segments
// for 10 buffers, the case in which the new code refuses frames and the wake has to keep TCP going.
static void throughput(int flows, int rtt, bool expect_refusals)
{
    Result r[2];
    for (int m = 0; m < 2; m++) {
        int64_t t0 = start(m ? new_model : old_model, rtt, flows);
        Result a = result();
        run_until(t0 + 10 * SEC);
        r[m] = since(a, result());
        print("throughput", m ? "new" : "old", rtt, flows, 10.0, r[m]);
    }
    EXPECT_TRUE(r[0].delivered > 100000); // the stream does flow
    double ratio = (double)r[1].delivered / (double)r[0].delivered;
    fprintf(stdout, "WTXSIM throughput flows=%d rtt=%dms new/old delivered = %.4f\n", flows, rtt, ratio);
    EXPECT_TRUE(ratio > 0.97 && ratio < 1.03);
    EXPECT_EQ(r[1].errors, 0);
    EXPECT_EQ(r[1].blocked_us, (int64_t)0);
    if (expect_refusals) {
        EXPECT_TRUE(r[1].refused > 0);
        EXPECT_TRUE(r[1].wakes > 0);
    }
}

