// ---- 2. The module stops draining for 3 seconds ---------------------------------------------
// A bulk stream, and a host that sends UDP to the device's WiFi address every 10 ms (lwIP answers
// over WiFi: the bench leg). From 2 s to 5 s the module does not drain the UART.
TEST(WtxSimStall, lwip_stays_responsive_and_tcp_resumes_with_the_drain)
{
    const int rtt = 30;
    Result r[2];
    int64_t resume_us[2];
    for (int m = 0; m < 2; m++) {
        int64_t t0 = start(m ? new_model : old_model, rtt);
        Result a = result();
        S.udp_every_us = 10000;
        post(now_us + 10000, EV_UDP);
        S.stall_from = t0 + 2 * SEC;
        S.stall_to = t0 + 5 * SEC;
        S.ping_max_us = 0;
        run_until(t0 + 8 * SEC);
        r[m] = since(a, result());
        resume_us[m] = first_accept_after(S.stall_to);
        print("stall", m ? "new" : "old", rtt, 1, 8.0, r[m]);
        fprintf(stdout, "WTXSIM stall model=%s first TCP frame taken after the drain resumed: %.1f ms (RTT %d ms)\n",
                m ? "new" : "old", resume_us[m] / 1000.0, rtt);
    }
    // the old wait: lwIP is stopped for the whole stall (the core lock is held), and so is every ping
    EXPECT_TRUE(r[0].blocked_us > 2900000);
    EXPECT_TRUE(r[0].ping_max_us > 2900000);
    // the new: no wait, every ping is taken in a tick or two (the timer tick is 5 ms), and TCP is
    // taken from the pool as soon as the first frame has left the module: a frame time, not a round trip
    EXPECT_EQ(r[1].blocked_us, (int64_t)0);
    EXPECT_TRUE(r[1].ping_max_us <= 2 * TICK);
    EXPECT_TRUE(r[1].refused > 0);
    EXPECT_TRUE(resume_us[1] >= 0 && resume_us[1] < 10000);
    EXPECT_EQ(r[1].errors, 0);
}

// ---- 3. Nothing in flight, the pool taken by other traffic -----------------------------------
// TCP has nothing outstanding, so no ACK is coming to restart it: after the pool is taken by 12
// datagrams, the segment lwIP was refused is sent when the first datagram has left the module, or, with
// no wake, when lwIP's poll finds it (a second or two)
TEST(WtxSimWake, a_refused_segment_is_sent_when_the_pool_has_room)
{
    const int rtt = 30;
    int64_t first[2];
    for (int m = 0; m < 2; m++) {
        start(m ? new_model : old_model, rtt);
        // quiet: the stream stops, everything is acknowledged
        S.flow[0].app_on = false;
        run_until(now_us + 3 * SEC);
        ASSERT_TRUE(S.flow[0].pcb->unacked == NULL && S.flow[0].pcb->unsent == NULL);
        int refused0 = S.refused;
        int64_t burst = now_us + 10000;
        post(burst, EV_BURST);
        S.flow[0].app_on = true;
        post(burst, EV_APP, std::vector<uint8_t>(1, 0)); // after the datagrams: the application writes again
        run_until(burst + 3 * SEC);
        first[m] = first_accept_after(burst);
        fprintf(stdout, "WTXSIM wake model=%s: TCP frame taken %.1f ms after the other traffic took the pool "
                "(refused %d, wake posts %d)\n", m ? "new" : "old", first[m] / 1000.0, S.refused - refused0, txnow_posts);
        if (m) {
            EXPECT_TRUE(S.refused > refused0); // the segment really was refused
        }
    }
    EXPECT_TRUE(first[0] >= 0 && first[0] < 10000); // the old wait: until a buffer is free
    EXPECT_TRUE(first[1] >= 0 && first[1] < 10000); // the wake: the same
}
