BaseType_t drop_callback(command_buf_context_t *, command_buf_t *, BaseType_t *) { return pdFALSE; }

// The firmware's DmaUART on the model, wired to wifi.cc as WiFi::Init does (wifi_tx_wake_init)
struct Rig {
    command_buf_context_t ctx;
    dma_uart_t regs;
    DmaUART *uart;
    uint8_t frame[1514];

    Rig(bool wake_init = true)
    {
        dmauart_hw().reset_all();
        memset(&net_counters, 0, sizeof(net_counters));
        memset(&ctx, 0, sizeof(ctx));
        memset(frame, 0x5A, sizeof(frame));
        cmd_buffer_init(&ctx);
        uart = new DmaUART(&regs, 3, NULL, &ctx);
        uart->SetReceiveCallback(drop_callback);
        esp32.uart = uart;
        wifi.state = eWifi_Connected;
        host_longest_wait_asked = 0;
        host_queue_wait = NULL;
        host_count_hook = NULL;
        posts = txnow_runs = 0;
        post_result = ERR_OK;
        msg_alloc_fails = false;
        wifi_txnow_msg = NULL;
        wifi_tx_starved = 0;
        if (wake_init) {
            wifi_tx_wake_init(uart);
        }
    }
    ~Rig() { delete uart; }

    uint8_t isr() { return DmaUART::DmaUartInterrupt(uart); }
    size_t free_tx() const { return uxQueueMessagesWaitingFromISR(ctx.freeTxQueue); }
    // lwIP offers a frame
    err_t send() { return wifi_tx_packet(NULL, frame, sizeof(frame)); }
    // The module drains one frame: the first interrupt starts the frame at the head of the queue,
    // each later one finishes the frame on the wire and starts the next
    void start() { isr(); }
    uint8_t finish_frame()
    {
        dmauart_hw().tx_complete();
        return isr();
    }
    // A request: what BUFARGS does
    BaseType_t rpc_buffer(command_buf_t **b) { return uart->GetBuffer(b, 1000); }
    // Offers frames until the pool is down to 'left' free, the first one on the wire
    void fill_to(size_t left)
    {
        while (free_tx() > left) {
            ASSERT_EQ(send(), ERR_OK);
            if (dmauart_hw().tx_pushes == 0) {
                start();
            }
        }
    }
};

