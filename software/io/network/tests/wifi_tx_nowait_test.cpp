// The wait itself ----------------------------------------------------------------------------

// The pool down to the reserve: the frame is refused with ERR_MEM, and nothing waited
TEST(WifiTxNoWait, refuses_at_the_reserve_without_waiting)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    ASSERT_EQ(r.free_tx(), (size_t)WIFI_TX_RESERVE);
    EXPECT_EQ(r.send(), ERR_MEM);
    EXPECT_EQ(host_longest_wait_asked, (TickType_t)0);
    EXPECT_EQ(net_counters.wifi_tx_refused, (uint32_t)1);
    EXPECT_EQ(r.free_tx(), (size_t)WIFI_TX_RESERVE); // nothing was taken
}

// Whatever the pool holds: an empty one refuses at once too
TEST(WifiTxNoWait, refuses_with_the_pool_empty_without_waiting)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    command_buf_t *a, *b;
    ASSERT_EQ(r.rpc_buffer(&a), pdTRUE);
    ASSERT_EQ(r.rpc_buffer(&b), pdTRUE);
    ASSERT_EQ(r.free_tx(), (size_t)0);
    host_longest_wait_asked = 0;
    EXPECT_EQ(r.send(), ERR_MEM);
    EXPECT_EQ(host_longest_wait_asked, (TickType_t)0);
}

// A request is still admitted from the reserve
TEST(WifiTxNoWait, a_request_is_admitted_from_the_reserve)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    EXPECT_EQ(r.send(), ERR_MEM); // the data frame is not
    command_buf_t *a, *b, *c;
    EXPECT_EQ(r.rpc_buffer(&a), pdTRUE);
    EXPECT_EQ(r.rpc_buffer(&b), pdTRUE);
    EXPECT_EQ(r.free_tx(), (size_t)0);
    EXPECT_EQ(r.rpc_buffer(&c), pdFALSE); // and only the reserve: the request waits for the rest, as before
    EXPECT_EQ(host_longest_wait_asked, (TickType_t)1000);
}

// Above the reserve a frame is admitted, and leaves the reserve alone
TEST(WifiTxNoWait, a_frame_is_admitted_above_the_reserve)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE + 1);
    EXPECT_EQ(r.send(), ERR_OK);
    EXPECT_EQ(r.free_tx(), (size_t)WIFI_TX_RESERVE);
    EXPECT_EQ(net_counters.wifi_tx_refused, (uint32_t)0);
    EXPECT_EQ(host_longest_wait_asked, (TickType_t)0);
}

// The frame that got a buffer is the same frame as before: header, length, payload, size
TEST(WifiTxNoWait, the_frame_in_the_buffer_is_unchanged)
{
    Rig r;
    ASSERT_EQ(r.send(), ERR_OK);
    command_buf_t *b = NULL;
    ASSERT_EQ(cmd_buffer_get_tx_isr(&r.ctx, &b, NULL), pdTRUE);
    rpc_send_eth_req *args = (rpc_send_eth_req *)b->data;
    EXPECT_EQ(args->hdr.command, CMD_SEND_PACKET);
    EXPECT_EQ(args->hdr.thread, 0xFF);
    EXPECT_EQ(args->length, (uint32_t)1514);
    EXPECT_EQ(b->size, (int)(sizeof(rpc_send_eth_req) + 1514 - 4));
    EXPECT_TRUE(memcmp(&args->data, r.frame, 1514) == 0);
}

// Not connected (a scan): ERR_CONN before any buffer is looked at, as before
TEST(WifiTxNoWait, not_connected_is_refused_before_the_pool)
{
    Rig r;
    wifi.state = eWifi_NotConnected;
    EXPECT_EQ(r.send(), ERR_CONN);
    EXPECT_EQ(r.free_tx(), (size_t)NUM_TX_BUFFERS);
    EXPECT_EQ(net_counters.wifi_tx_refused, (uint32_t)0);
}

// The counters: frames that got a buffer are in the first bucket, the longest wait stays 0
TEST(WifiTxNoWait, counters)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    EXPECT_EQ(net_counters.wifi_tx_wait[0], (uint32_t)(NUM_TX_BUFFERS - WIFI_TX_RESERVE));
    EXPECT_EQ(net_counters.wifi_tx_wait[NET_WTX_TIMEOUT], (uint32_t)0);
    EXPECT_EQ(net_counters.wifi_tx_wait_max, (uint32_t)0);
    r.send();
    r.send();
    EXPECT_EQ(net_counters.wifi_tx_refused, (uint32_t)2);
}

// The wake -----------------------------------------------------------------------------------

// The TX-done interrupt posts nothing while no frame was refused
TEST(WifiTxWake, no_post_without_a_refusal)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE + 1);
    for (int i = 0; i < 5; i++) {
        r.finish_frame();
    }
    EXPECT_EQ(posts, 0);
}

// A frame that finishes on the wire after a refusal, with the pool above the reserve: one post, once
TEST(WifiTxWake, a_refusal_is_followed_by_exactly_one_post)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    EXPECT_EQ(r.send(), ERR_MEM);
    EXPECT_EQ(posts, 0);
    EXPECT_TRUE(wifi_tx_starved != 0);
    r.finish_frame(); // the first frame is done: 3 free
    EXPECT_EQ(posts, 1);
    EXPECT_TRUE(wifi_tx_starved == 0);
    for (int i = 0; i < 4; i++) {
        r.finish_frame();
    }
    EXPECT_EQ(posts, 1);
    // the callback the post stands for runs tcp_txnow()
    ASSERT_TRUE(registered_fn != NULL);
    registered_fn(NULL);
    EXPECT_EQ(txnow_runs, 1);
}

// At or below the reserve a finished frame does not wake: the sender would be refused again
TEST(WifiTxWake, no_post_while_the_pool_is_still_at_the_reserve)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    EXPECT_EQ(r.send(), ERR_MEM);
    command_buf_t *rpc;
    ASSERT_EQ(r.rpc_buffer(&rpc), pdTRUE); // a request takes one of the reserve: 1 free
    r.finish_frame();                      // 2 free
    EXPECT_EQ(r.free_tx(), (size_t)WIFI_TX_RESERVE);
    EXPECT_EQ(posts, 0);
    EXPECT_TRUE(wifi_tx_starved != 0);     // still waiting for room
    r.finish_frame();                      // 3 free
    EXPECT_EQ(posts, 1);
}

// The post asks the interrupt to switch context when the queue post woke the tcpip thread
TEST(WifiTxWake, the_interrupt_switches_when_the_post_woke_a_task)
{
    {
        Rig r;
        r.fill_to(WIFI_TX_RESERVE);
        r.send();
        post_result = ERR_NEED_SCHED;
        EXPECT_TRUE(r.finish_frame() != 0);
    }
    {
        Rig r;
        r.fill_to(WIFI_TX_RESERVE);
        r.send();
        post_result = ERR_OK;
        EXPECT_EQ(r.finish_frame(), (uint8_t)0);
    }
}

// A buffer freed between the check and the flag woke nobody; the second look takes it
TEST(WifiTxWake, a_buffer_freed_before_the_flag_is_taken_by_the_second_look)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    static Rig *rig;
    rig = &r;
    // the first count read (free == reserve) is followed by the interrupt: the frame on the wire is
    // done, and the flag is not up yet
    host_count_hook = [] { rig->finish_frame(); };
    EXPECT_EQ(r.send(), ERR_OK);
    EXPECT_EQ(posts, 0);
    EXPECT_EQ(net_counters.wifi_tx_refused, (uint32_t)0);
    EXPECT_EQ(r.free_tx(), (size_t)WIFI_TX_RESERVE);
}

// The tcpip mailbox full (ERR_MEM): the wake is not lost, the next freed buffer posts again
TEST(WifiTxWake, a_full_mailbox_keeps_the_flag_and_the_next_free_posts_again)
{
    Rig r;
    r.fill_to(WIFI_TX_RESERVE);
    r.send();
    post_result = ERR_MEM;
    EXPECT_EQ(r.finish_frame(), (uint8_t)0);
    EXPECT_EQ(posts, 1);
    EXPECT_TRUE(wifi_tx_starved != 0);
    post_result = ERR_OK;
    r.finish_frame();
    EXPECT_EQ(posts, 2);
    EXPECT_TRUE(wifi_tx_starved == 0);
}

// No allocation of the message (lwIP out of memory): nothing is posted and nothing breaks
TEST(WifiTxWake, no_message_no_post)
{
    Rig r(false);
    msg_alloc_fails = true;
    wifi_tx_wake_init(r.uart);
    r.fill_to(WIFI_TX_RESERVE);
    EXPECT_EQ(r.send(), ERR_MEM);
    r.finish_frame();
    EXPECT_EQ(posts, 0);
}

// The interrupt calls nothing before the WiFi code registers, and nothing after the module's
// application ended (ResetReceiveCallback is what esp32.cc and WiFi::Terminate call)
TEST(WifiTxWake, hook_only_between_init_and_reset)
{
    {
        Rig r(false);
        wifi_tx_starved = 1;
        r.fill_to(WIFI_TX_RESERVE + 1);
        r.finish_frame();
        r.finish_frame();
        EXPECT_EQ(posts, 0);
    }
    {
        Rig r;
        r.fill_to(WIFI_TX_RESERVE);
        r.send();
        r.uart->ResetReceiveCallback();
        r.finish_frame();
        EXPECT_EQ(posts, 0);
    }
}
