#!/usr/bin/env python3
"""E2E: a stream start without a wired Ethernet address names the wired link.

The VIC and audio streams are generated by the FPGA and leave through the wired
Ethernet port only. When that port has no link or no IP address, a start is
refused with HTTP 500 and the error "Wired Ethernet link is down or has no IP
address", even while WiFi is connected and carries the request.

On a device whose Ethernet and WiFi share this host's subnet, the suite sets the
Ethernet port to a static 0.0.0.0 over WiFi, starts the video stream over WiFi,
and requires that refusal with no packet arriving. It then gives the port its
address back and requires the stream to start again over Ethernet. A device
that already refuses a start for want of a wired link is checked as it is.

Every stream here goes to a multicast group, so no check depends on resolving
this host's hardware address. The settings are changed in memory only, but
three effects last until the device restarts, so power-cycle it afterwards:

- Switching the port to static releases its DHCP lease, and the port then holds
  the same address statically. The DHCP server may hand that address to
  another host in the meantime.
- The device's DNS server becomes the "Static DNS" setting.
- The port keeps its address as a static one with this host's netmask and
  gateway, because switching DHCP on again does not restart the DHCP client
  while the link stays up. "Use DHCP" reads its original value again.

    ./run-tests --suite stream-wired-link u64
"""

import argparse
import ipaddress
import json
import re
import socket
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

# The one stanza that puts the shared library on sys.path; see tests/lib/bootstrap.py.
sys.path.insert(0, str(next(p for p in Path(__file__).resolve().parents
                            if (p / "tests" / "lib").is_dir()) / "tests" / "lib"))
import bootstrap  # noqa: E402,F401
import cli  # noqa: E402

import machine as machine_lib  # noqa: E402
import streams  # noqa: E402
import targets  # noqa: E402
from api import UltimateApi  # noqa: E402
from report import (Failure, check, check_skip, check_start, detail,  # noqa: E402
                    format_exception, suite_fail, suite_ok, suite_skip,
                    teardown_step)

SUITE = "stream_wired_link_test"

REFUSAL = "Wired Ethernet link is down or has no IP address"
VIDEO_SOURCE_PORT = 53248
# A quarter of the roughly 3400 video packets one second carries.
MIN_VIDEO_PACKETS = 800

LISTEN_SECONDS = 1.0
SETTLE_SECONDS = 0.5
IDENT_PORT = 64
IDENT_SECONDS = 1.0

ETHERNET = "Ethernet Settings"
ETHERNET_ITEMS = ("Use DHCP", "Static IP", "Static Netmask", "Static Gateway",
                  "Static DNS")
LABEL = "a start over WiFi without a wired address names the Ethernet link"


def standard_groups(target: targets.Target) -> dict[str, tuple[str, int]]:
    """Where each stream goes when nothing else asks for it, as a recorder expects."""
    return {"video": (target.video_group, target.video_port),
            "audio": (target.audio_group, target.audio_port)}


def local_address(towards: str) -> str:
    """This host's address on the route to `towards`."""
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.connect((towards, 9))
        return sock.getsockname()[0]


def collect(sock: socket.socket, seconds: float) -> Counter:
    """Every datagram within `seconds`, counted by (sender, port, size)."""
    seen: Counter = Counter()
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        try:
            data, sender = sock.recvfrom(2048)
        except TimeoutError:
            continue
        seen[(sender[0], sender[1], len(data))] += 1
    return seen


def senders_on_groups(target: targets.Target) -> dict[str, set[str]]:
    """Who is sending each stream to its standard group right now."""
    senders = {}
    for name, group in standard_groups(target).items():
        sock = streams.stream_socket(*group, timeout=0.1)
        try:
            senders[name] = {key[0] for key in collect(sock, SETTLE_SECONDS)}
        finally:
            sock.close()
    return senders


def start_video(api: UltimateApi, group: str) -> tuple[int, str, Counter]:
    """Start video to `group` on a port of this suite's own: the answer, and
    what arrived. Another device streaming to the group uses another port, so
    everything that arrives comes from this device."""
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        sock.bind(("", 0))
        sock.setsockopt(socket.IPPROTO_IP, socket.IP_ADD_MEMBERSHIP,
                        socket.inet_aton(group) + socket.inet_aton("0.0.0.0"))
        sock.settimeout(0.1)
        code, _, body = api.rest.request(
            "PUT", "/v1/streams/video:start",
            params={"ip": f"{group}:{sock.getsockname()[1]}"})
        return code, body.decode("utf-8", "replace"), collect(sock, LISTEN_SECONDS)
    finally:
        sock.close()


def stream_sender(seen: Counter) -> str:
    """The address the stream came from, which is the wired port's."""
    senders = {key[0] for key in seen}
    if len(senders) != 1:
        raise Failure(f"expected the stream from one address, got {sorted(senders) or 'none'}")
    return senders.pop()


def expect_refusal(code: int, body: str) -> None:
    """Raise unless the answer is the refusal for a missing wired link."""
    detail(f"HTTP {code}: {' '.join(body.split())}")
    try:
        errors = json.loads(body).get("errors", [])
    except ValueError:
        errors = []
    if code != 500 or REFUSAL not in errors:
        raise Failure(f"expected HTTP 500 {REFUSAL!r}, got HTTP {code} {errors}")


def ident_addresses(unique_id: str, local: str) -> set[str]:
    """The addresses that answer an ident broadcast as this device."""
    found = set()
    nonce = f"streams-{time.monotonic_ns()}"
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
        sock.bind((local, 0))
        sock.settimeout(0.1)
        sock.sendto(f"json{nonce}".encode("ascii"), ("255.255.255.255", IDENT_PORT))
        deadline = time.monotonic() + IDENT_SECONDS
        while time.monotonic() < deadline:
            try:
                payload, sender = sock.recvfrom(4096)
                answer = json.loads(payload.decode("utf-8"))
            except (OSError, ValueError):
                continue
            if answer.get("your_string") == nonce and answer.get("unique_id") == unique_id:
                found.add(sender[0])
    return found


def wireless_address(api: UltimateApi, info, wired: str, local: str) -> str | None:
    """The device's address other than the wired one: the addressed host when
    that is not the wired port, otherwise one that answered the ident broadcast."""
    addressed = socket.gethostbyname(api.host)
    if addressed != wired:
        return addressed
    others = ident_addresses(str(info.extra.get("unique_id", "")), local) - {wired}
    return sorted(others)[0] if others else None


def host_route(local: str, wired: str) -> tuple[str, str] | None:
    """This host's netmask and default gateway, when the wired address is on
    this host's subnet; otherwise None."""
    try:
        addrs = subprocess.run(["ip", "-o", "-4", "addr", "show"], capture_output=True,
                               text=True, check=False).stdout
        routes = subprocess.run(["ip", "-4", "route", "show", "default"],
                                capture_output=True, text=True, check=False).stdout
    except OSError:
        return None
    found = re.search(rf"\binet {re.escape(local)}/(\d+)", addrs)
    if not found:
        return None
    network = ipaddress.ip_network(f"{local}/{found.group(1)}", strict=False)
    if ipaddress.ip_address(wired) not in network:
        return None
    for gateway in re.findall(r"default via (\S+)", routes):
        if ipaddress.ip_address(gateway) in network:
            return str(network.netmask), gateway
    return None


def remove_wired_address(wireless: UltimateApi, wired: str, local: str,
                         group: str) -> bool:
    """The refused start; answers whether the address was changed at all."""
    route = host_route(local, wired)
    if route is None:
        check_start(LABEL)
        check_skip("the wired address is not on this host's subnet, or this host's "
                   "netmask and gateway are unknown, so it could not be restored")
        return False
    netmask, gateway = route
    original = {item: wireless.configs.current(ETHERNET, item) for item in ETHERNET_ITEMS}
    detail(f"Ethernet settings: {original}")
    try:
        with check(LABEL):
            # "Use DHCP" applies nothing by itself, so a static item goes last.
            wireless.configs.set(ETHERNET, "Use DHCP", "Disabled")
            wireless.configs.set(ETHERNET, "Static IP", "0.0.0.0")
            time.sleep(SETTLE_SECONDS)
            code, body, seen = start_video(wireless, group)
            if code == 200:
                wireless.streams.stop("video")
            expect_refusal(code, body)
            if seen:
                raise Failure(f"packets arrived after a refused start: {dict(seen)}")
    finally:
        # One item at a time, the address last, because writing it applies all.
        for item, value in (("Static Netmask", netmask), ("Static Gateway", gateway),
                            ("Static IP", wired)):
            teardown_step(f"set {item} to {value}",
                          lambda item=item, value=value:
                          wireless.configs.set(ETHERNET, item, value))
        for item in ETHERNET_ITEMS:
            teardown_step(f"restore {item}",
                          lambda item=item: wireless.configs.set(ETHERNET, item, original[item]))
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    cli.add_device_arguments(parser)
    args = parser.parse_args()
    password = args.password or None

    target = targets.resolve(args.host)
    api = UltimateApi(args.host, password, args.timeout)
    info = api.info()
    machine = machine_lib.identify(target.device, lambda: (str(info.product),
                                                           str(info.firmware_version)))
    if not machine.has_data_streams:
        suite_skip(SUITE, f"{machine.described} has no data streams")
        return 0

    failure = ""
    running: set[str] = set()
    try:
        before = senders_on_groups(target)
        group = target.video_group
        code, body, seen = start_video(api, group)
        if code != 200:
            # A device that already has no wired address is checked as it is.
            with check(LABEL.replace(" over WiFi", "")):
                expect_refusal(code, body)
            suite_ok(SUITE, "the device has no wired address")
            return 0
        try:
            wired = stream_sender(seen)
        except Failure:
            api.streams.stop("video")
            raise
        running = {name for name, senders in before.items() if wired in senders}
        api.streams.stop("video")
        local = local_address(socket.gethostbyname(target.device))
        wireless = wireless_address(api, info, wired, local)
        detail(f"wired {wired}, wireless {wireless or 'none'}, this host {local}")
        if wireless is None:
            check_start(LABEL)
            check_skip("the device has no WiFi address on this host's subnet")
        elif remove_wired_address(UltimateApi(wireless, password, args.timeout),
                                  wired, local, group):
            with check("the stream starts again over Ethernet once it has its address"):
                time.sleep(SETTLE_SECONDS)
                wired_api = UltimateApi(wired, password, args.timeout)
                code, body, seen = start_video(wired_api, group)
                if code != 200:
                    raise Failure(f"video:start returned HTTP {code}: {' '.join(body.split())}")
                wired_api.streams.stop("video")
                ours = sum(n for (sender, port, size), n in seen.items()
                           if sender == wired and port == VIDEO_SOURCE_PORT
                           and size == streams.VIDEO_PACKET_BYTES)
                if ours < MIN_VIDEO_PACKETS:
                    raise Failure(f"{ours} video packets from {wired} in "
                                  f"{LISTEN_SECONDS:.1f}s, expected at least "
                                  f"{MIN_VIDEO_PACKETS}; saw {dict(seen)}")
                detail(f"{ours} packets from {wired}:{VIDEO_SOURCE_PORT}")
    except Failure as exc:
        failure = str(exc)
    except Exception as exc:  # noqa: BLE001
        failure = format_exception(exc)
    finally:
        # Leave the standard streams as they were found, for a recorder.
        for name in sorted(running):
            group_port = standard_groups(target)[name]
            teardown_step(f"restart {name}", lambda name=name, group_port=group_port:
                          api.streams.start(name, ip=f"{group_port[0]}:{group_port[1]}"))

    if failure:
        suite_fail(SUITE, failure)
        return 1
    suite_ok(SUITE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
