#!/usr/bin/env python3
"""E2E: which network interface the data streams use, whichever one asked.

The VIC and audio streams are generated by the FPGA and sent by the wired
Ethernet port. The REST call that starts or stops them can arrive over Ethernet
or over WiFi. This suite checks both facts on one device:

- `routing`: every pairing of the interface that starts a stream with the
  interface that stops it, for video and audio to a unicast address on this
  host, and for video to the multicast group. Each started stream has to arrive
  from the wired address with the stream's own source port and packet size, and
  each stopped stream has to fall silent. A device that answers on only one
  address runs the one pairing it has and skips the others.
- `no-wired-address`: with the Ethernet port left without an IP address, a
  start sent over WiFi has to be refused with an error that names the wired
  Ethernet link, and no packet may arrive.

`no-wired-address` needs WiFi and Ethernet on this host's subnet. It sets the
Ethernet port to a static 0.0.0.0 and back again, in memory only. The port gets
its address back as a static one with this host's netmask and gateway, because
switching DHCP on again does not restart the DHCP client while the link stays
up. "Use DHCP" reads its original value again afterwards, and the next restart
returns the port to it.

    ./run-tests --suite stream-interfaces u64
    ./run-tests --suite stream-no-wired-address u64
"""

import argparse
import ipaddress
import json
import re
import socket
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

# The one stanza that puts the shared library on sys.path; see tests/lib/bootstrap.py.
sys.path.insert(0, str(next(p for p in Path(__file__).resolve().parents
                            if (p / "tests" / "lib").is_dir()) / "tests" / "lib"))
import bootstrap  # noqa: E402,F401
import cli  # noqa: E402

import machine as machine_lib  # noqa: E402
import streams  # noqa: E402
import targets  # noqa: E402
from api import UltimateApi  # noqa: E402
from report import (Failure, check, check_skip, check_start, detail,  # noqa: E402
                    format_exception, suite_fail, suite_ok, suite_skip,
                    teardown_step)

SUITE = "stream_interfaces_test"

# Source port and datagram size of each stream, from DataStreamer.
STREAM_SOURCE = {"video": (53248, streams.VIDEO_PACKET_BYTES),
                 "audio": (54272, streams.AUDIO_PACKET_BYTES)}
# Video sends about 3400 packets a second and audio 250; these are a quarter
# of what one second carries, so a slow start does not fail a check.
MIN_PACKETS = {"video": 800, "audio": 60}

LISTEN_SECONDS = 1.0
# Packets already on the wire when the stop was answered.
DRAIN_SECONDS = 0.3
IDENT_PORT = 64
IDENT_SECONDS = 1.0
SETTLE_SECONDS = 0.5

ETHERNET = "Ethernet Settings"
ETHERNET_ITEMS = ("Use DHCP", "Static IP", "Static Netmask", "Static Gateway",
                  "Static DNS")


def local_address(towards: str) -> str:
    """This host's address on the route to `towards`."""
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.connect((towards, 9))
        return sock.getsockname()[0]


def bound_socket(group: str | None) -> tuple[socket.socket, int]:
    """A socket receiving unicast on a free port, or the multicast `group`."""
    if group is None:
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        sock.bind(("", 0))
        sock.settimeout(0.1)
        return sock, sock.getsockname()[1]
    port = streams.VIDEO_PORT
    return streams.stream_socket(group, port, timeout=0.1), port


def listen(sock: socket.socket, seconds: float) -> Counter:
    """Every datagram within `seconds`, counted by (sender, port, size)."""
    seen: Counter = Counter()
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        try:
            data, sender = sock.recvfrom(2048)
        except TimeoutError:
            continue
        seen[(sender[0], sender[1], len(data))] += 1
    return seen


def drain(sock: socket.socket) -> None:
    sock.setblocking(False)
    try:
        while True:
            sock.recvfrom(2048)
    except OSError:
        pass
    finally:
        sock.settimeout(0.1)


def start(api: UltimateApi, stream: str, address: str, **params) -> tuple[int, str]:
    code, _, body = api.rest.request("PUT", f"/v1/streams/{stream}:start",
                                     params={"ip": address, **params})
    return code, body.decode("utf-8", "replace")


def stop(api: UltimateApi, stream: str) -> None:
    api.streams.stop(stream)


def ident_addresses(unique_id: str, local: str) -> set[str]:
    """The addresses that answer an ident broadcast as this device."""
    found = set()
    nonce = f"streams-{time.monotonic_ns()}"
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
        sock.bind((local, 0))
        sock.settimeout(0.1)
        sock.sendto(f"json{nonce}".encode("ascii"), ("255.255.255.255", IDENT_PORT))
        deadline = time.monotonic() + IDENT_SECONDS
        while time.monotonic() < deadline:
            try:
                payload, sender = sock.recvfrom(4096)
                answer = json.loads(payload.decode("utf-8"))
            except (OSError, ValueError):
                continue
            if answer.get("your_string") == nonce and answer.get("unique_id") == unique_id:
                found.add(sender[0])
    return found


def is_device(address: str, unique_id: str, password: str | None) -> bool:
    try:
        info = UltimateApi(address, password, 2.0).info()
    except (Failure, OSError):
        return False
    return info.extra.get("unique_id") == unique_id


def wired_address(api: UltimateApi, unique_id: str, password: str | None,
                  before: set[str]) -> str:
    """The address the stream comes from, which is the Ethernet port's.

    Found over multicast, which needs no ARP, so the unicast checks meet a
    wired port that has not yet resolved this host.
    """
    sock = streams.stream_socket(streams.AUDIO_GROUP, streams.AUDIO_PORT, timeout=0.1)
    try:
        code, body = start(api, "audio", f"{streams.AUDIO_GROUP}:{streams.AUDIO_PORT}")
        if code != 200:
            raise Failure(f"audio:start returned HTTP {code}: {body[:160]!r}")
        senders = listen(sock, LISTEN_SECONDS)
        stop(api, "audio")
    finally:
        sock.close()
    # A sender that appeared with this start is this device. Asking a sender
    # for its id is the fallback, because any request to the wired address
    # teaches it this host's MAC and so would hide the case under test.
    new = {key[0] for key in senders} - before
    if len(new) == 1:
        return new.pop()
    for (sender, _, _), _ in senders.most_common():
        if is_device(sender, unique_id, api.rest.password):
            return sender
    raise Failure("no audio packet arrived from this device, so the wired address is unknown")


def expect_stream(sock: socket.socket, stream: str, wired: str,
                  wireless: set[str]) -> str:
    """Raise unless `stream` arrives from the wired address and none of it
    from the device's wireless one. Another device on the group is ignored."""
    seen = listen(sock, LISTEN_SECONDS)
    port, size = STREAM_SOURCE[stream]
    ours = sum(n for (sender, sport, length), n in seen.items()
               if sender == wired and sport == port and length == size)
    stray = {key: n for key, n in seen.items() if key[0] in wireless}
    if stray:
        raise Failure(f"packets from the wireless address: {stray}")
    if ours < MIN_PACKETS[stream]:
        raise Failure(f"{ours} {stream} packets from {wired}:{port} in "
                      f"{LISTEN_SECONDS:.1f}s, expected at least {MIN_PACKETS[stream]}; "
                      f"saw {dict(seen)}")
    return f"{ours} packets from {wired}:{port}"


def expect_silence(sock: socket.socket, wired: str) -> None:
    time.sleep(DRAIN_SECONDS)
    drain(sock)
    seen = listen(sock, LISTEN_SECONDS)
    late = sum(n for key, n in seen.items() if key[0] == wired)
    if late:
        raise Failure(f"{late} packets from {wired} after the stop")


def routing(apis: dict[str, UltimateApi], wired: str, wireless: set[str],
            local: str) -> None:
    # WiFi first: the first unicast start then meets a wired port that has not
    # resolved this host, which is the case a start over WiFi has to handle.
    names = sorted(apis, reverse=True)
    pairs = [(a, b) for a in names for b in names]
    for stream, group in (("video", None), ("audio", None),
                          ("video", streams.VIDEO_GROUP)):
        where = "multicast" if group else "unicast"
        for via_start, via_stop in pairs:
            label = (f"{stream} {where}: start over {via_start}, "
                     f"stop over {via_stop}")
            sock, port = bound_socket(group)
            try:
                with check(label):
                    code, body = start(apis[via_start], stream,
                                       f"{group or local}:{port}")
                    if code != 200:
                        raise Failure(f"start returned HTTP {code}: {body[:160]!r}")
                    detail(expect_stream(sock, stream, wired, wireless))
                    stop(apis[via_stop], stream)
                    expect_silence(sock, wired)
            finally:
                sock.close()
                teardown_step(f"stop {stream}", lambda: stop(apis[via_stop], stream))
        if len(names) == 1:
            check_start(f"{stream} {where}: start and stop over different interfaces")
            check_skip("the device answers on one address only")


def host_route(local: str) -> tuple[str, str] | None:
    """This host's netmask and default gateway for `local`, or None."""
    try:
        addrs = subprocess.run(["ip", "-o", "-4", "addr", "show"], capture_output=True,
                               text=True, check=False).stdout
        routes = subprocess.run(["ip", "-4", "route", "show", "default"],
                                capture_output=True, text=True, check=False).stdout
    except OSError:
        return None
    found = re.search(rf"\binet {re.escape(local)}/(\d+)", addrs)
    if not found:
        return None
    network = ipaddress.ip_network(f"{local}/{found.group(1)}", strict=False)
    for gateway in re.findall(r"default via (\S+)", routes):
        if ipaddress.ip_address(gateway) in network:
            return str(network.netmask), gateway
    return None


def no_wired_address(wireless: UltimateApi, wired_api: UltimateApi, wired: str,
                     wireless_addresses: set[str], local: str) -> None:
    label = "start over WiFi without a wired address names the Ethernet link"
    route = host_route(local)
    if route is None:
        check_start(label)
        check_skip("cannot find this host's netmask and gateway to restore the wired address")
        return
    netmask, gateway = route
    original = {item: wireless.configs.current(ETHERNET, item) for item in ETHERNET_ITEMS}
    detail(f"Ethernet settings: {original}")
    sock, port = bound_socket(None)
    try:
        with check(label):
            # "Use DHCP" applies nothing by itself, so a static item goes last.
            wireless.configs.set(ETHERNET, "Use DHCP", "Disabled")
            wireless.configs.set(ETHERNET, "Static IP", "0.0.0.0")
            time.sleep(SETTLE_SECONDS)
            code, body = start(wireless, "video", f"{local}:{port}")
            detail(f"HTTP {code}: {body.strip()}")
            if code == 200:
                stop(wireless, "video")
                raise Failure("the start was accepted with no wired address")
            errors = json.loads(body).get("errors", [])
            if code != 500 or not any("Ethernet" in e for e in errors):
                raise Failure(f"expected HTTP 500 naming the Ethernet link, got "
                              f"HTTP {code} {errors}")
            late = sum(listen(sock, LISTEN_SECONDS).values())
            if late:
                raise Failure(f"{late} packets arrived after a refused start")
    finally:
        sock.close()
        teardown_step("give the wired port its address back", lambda: (
            wireless.configs.set(ETHERNET, "Static Netmask", netmask),
            wireless.configs.set(ETHERNET, "Static Gateway", gateway),
            wireless.configs.set(ETHERNET, "Static IP", wired)))
        for item in ETHERNET_ITEMS:
            teardown_step(f"restore {item}",
                          lambda item=item: wireless.configs.set(ETHERNET, item, original[item]))

    with check("streams start again over Ethernet once it has its address"):
        time.sleep(SETTLE_SECONDS)
        wired_api.info()
        sock, port = bound_socket(None)
        try:
            code, body = start(wired_api, "video", f"{local}:{port}")
            if code != 200:
                raise Failure(f"start returned HTTP {code}: {body[:160]!r}")
            detail(expect_stream(sock, "video", wired, wireless_addresses))
            stop(wired_api, "video")
        finally:
            sock.close()


def senders_on_groups() -> dict[str, set[str]]:
    """Who is sending each stream to its standard group right now."""
    senders = {}
    for stream, group, port in (("video", streams.VIDEO_GROUP, streams.VIDEO_PORT),
                                ("audio", streams.AUDIO_GROUP, streams.AUDIO_PORT)):
        sock = streams.stream_socket(group, port, timeout=0.1)
        try:
            senders[stream] = {key[0] for key in listen(sock, SETTLE_SECONDS)}
        finally:
            sock.close()
    return senders


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    cli.add_device_arguments(parser)
    parser.add_argument("--test", choices=("routing", "no-wired-address", "all"),
                        default="routing")
    args = parser.parse_args()

    host = targets.device_of(args.host)
    api = UltimateApi(args.host, args.password or None, args.timeout)
    info = api.info()
    machine = machine_lib.identify(host, lambda: (str(info.product),
                                                  str(info.firmware_version)))
    if not machine.has_data_streams:
        suite_skip(SUITE, f"{machine.described} has no data streams")
        return 0

    failure = ""
    running: set[str] = set()
    try:
        local = local_address(socket.gethostbyname(host))
        unique_id = str(info.extra.get("unique_id", ""))
        before = senders_on_groups()
        wired = wired_address(api, unique_id, args.password or None, before["audio"])
        running = {stream for stream, senders in before.items() if wired in senders}
        addresses = ident_addresses(unique_id, local)
        addresses.add(socket.gethostbyname(host))
        wireless = sorted(addresses - {wired})
        wireless_set = set(wireless)
        detail(f"wired {wired}, wireless {wireless or 'none'}, this host {local}")
        apis = {"Ethernet": UltimateApi(wired, args.password or None, args.timeout)}
        if wireless:
            apis["WiFi"] = UltimateApi(wireless[0], args.password or None, args.timeout)

        if args.test in ("routing", "all"):
            routing(apis, wired, wireless_set, local)
        if args.test in ("no-wired-address", "all"):
            if "WiFi" in apis:
                no_wired_address(apis["WiFi"], apis["Ethernet"], wired, wireless_set,
                                 local)
            else:
                check_start("start over WiFi without a wired address names the Ethernet link")
                check_skip("the device has no WiFi address on this host's subnet")
    except Failure as exc:
        failure = str(exc)
    except Exception as exc:  # noqa: BLE001
        failure = format_exception(exc)
    finally:
        # Leave the standard streams as they were found, for a recorder.
        for stream in ("video", "audio"):
            if stream in running:
                teardown_step(f"restart {stream}", lambda stream=stream: api.streams.start(
                    stream, ip=streams.Arming(api, args.host).address(stream)))

    if failure:
        suite_fail(SUITE, failure)
        return 1
    suite_ok(SUITE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
